/// Ersatz für häufige Zeichen außerhalb von WinAnsi.
const Map<int, String> _fallback = {
  0x2192: '->', 0x2190: '<-', 0x2194: '<->', 0x21D2: '=>', 0x2264: '<=', 0x2265: '>=', 0x2260: '!=',
  0x2248: '~', 0x2212: '-', 0x2010: '-', 0x2011: '-', 0x00A0: ' ', 0x2009: ' ', 0x202F: ' ', 0x200B: '',
  0x2713: 'v', 0x2714: 'v', 0x2717: 'x', 0x2718: 'x', 0x25CF: '\u2022', 0x25E6: '\u2022', 0x25AA: '\u2022',
  0x2023: '\u2022', 0x2043: '-', 0x201B: "'", 0x201F: '"', 0x2032: "'", 0x2033: '"', 0x00AD: '',
};

/// Liefert die WinAnsi-Bytes eines Textes; unbekannte Zeichen werden ersetzt oder zu "?".
List<int> winAnsiEncode(String text) {
  final out = <int>[];
  for (final r in text.runes) {
    if (r < 0x80 || (r >= 0xA0 && r <= 0xFF)) {
      out.add(r < 0x20 ? 0x20 : r);
    } else if (_winAnsiHigh.containsKey(r)) {
      out.add(_winAnsiHigh[r]!);
    } else if (_fallback.containsKey(r)) {
      for (final c in _fallback[r]!.runes) {
        out.add(_winAnsiHigh[c] ?? (c < 0x100 ? c : 0x3F));
      }
    } else if (r >= 0x1F000 || (r >= 0x2600 && r <= 0x27BF) || (r >= 0xFE00 && r <= 0xFE0F)) {
      // Emojis und Symbole weglassen
    } else {
      out.add(0x3F);
    }
  }
  return out;
}
